#!/usr/bin/env python3
"""Dark panel artwork behind the controls, and the markers the chain picture strip finds the PICTURES page by. ORIGINAL art
(black glass, thin lines, a quiet wordmark); no brand, logo or copy of any real product.

    python3 tools/panel_art.py "<skin>/Plugin Skins"        (build.sh runs this after the skin is generated)
    python3 tools/panel_art.py --preview out.png            (just the artwork, 1280x628)

It never moves, resizes or restyles a control and never changes a label: it only replaces the pixels that are exactly the flat
plate colour (theme_panel) in the page background and in each page's panel image with the artwork at the same position, so every
control box, label and knob stays exactly as the skin builder drew it. Positions come from TUI.json (plugin pixels, 1280x628).
Then it paints two 2x2 marker blocks into the PICTURES page's panel image and writes build/chain_box.h (that image's place and size):
src/chainpics.c finds the page on the display by them, so the picture strip shows only while the PICTURES page is open.
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
W, H = 1280, 628
PLATE = (0x0e, 0x0e, 0x0e)          # theme_panel / theme_bg in layout.conf: the flat colour that gets replaced

MARK_TL = [(29, 11, 83), (83, 11, 29), (11, 83, 29), (29, 83, 11)]    # must match src/chainpics.c
MARK_BR = [(83, 29, 11), (11, 29, 83), (67, 11, 67), (11, 67, 67)]

HEADER_LINE_Y = 76      # a thin line under the header band (the picture strip lives above it)
FOOT_Y = 600            # the free band at the bottom (controls end at y 597)


def art():
    y = np.linspace(0, 1, H)[:, None, None]
    img = np.array([17, 17, 17], float)[None, None, :] * (1 - y) + np.array([9, 9, 9], float)[None, None, :] * y + np.zeros((H, W, 3))
    out = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8))
    d = ImageDraw.Draw(out)
    d.line((12, HEADER_LINE_Y, W - 12, HEADER_LINE_Y), fill=(46, 46, 46), width=2)
    d.line((12, FOOT_Y, W - 12, FOOT_Y), fill=(36, 36, 36), width=1)
    saira = ImageFont.truetype(os.path.join(ROOT, "art/fonts/SairaStencilOne-Regular.ttf"), 24)
    d.text((W // 2, (FOOT_Y + H) // 2 + 1), "THING4000", font=saira, fill=(86, 86, 86), anchor="mm")
    return out


def apply(skin_dir):
    tui = json.load(open(os.path.join(skin_dir, "TUI.json")))
    boxes = {}
    chain = {}

    def walk(o):
        if isinstance(o, dict):
            cd = o.get("componentData")
            if cd and isinstance(cd.get("data"), dict):
                im = str(cd["data"].get("image", ""))
                if im.startswith(("sh_bg_", "sh_mode_")):
                    b = [int(v) for v in o["bounds"]["bounds"].split()]
                    boxes[im] = b
                    if any("IndexedEnabling/8/" in str(h) for h in o["bounds"].get("additionalInvalidatingHandles", [])):
                        chain["image"] = im
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(tui)
    A = np.asarray(art(), dtype=np.uint8)
    n = 0
    for name, (bx, by, bw, bh) in boxes.items():
        p = os.path.join(skin_dir, name)
        im = np.array(Image.open(p).convert("RGB"))
        if im.shape[0] != bh or im.shape[1] != bw:
            raise SystemExit("panel_art: %s is %dx%d but TUI.json says %dx%d" % (name, im.shape[1], im.shape[0], bw, bh))
        mask = (im == np.array(PLATE, np.uint8)).all(axis=2)
        if name == chain.get("image"):
            for (x0, y0) in ((0, 0), (bw - 2, bh - 2)):
                if not mask[y0:y0 + 2, x0:x0 + 2].all():
                    raise SystemExit("panel_art: a control is drawn where the PICTURES page's marker block goes (%d,%d); move that control or the marker" % (x0, y0))
        crop = A[by:by + bh, bx:bx + bw]
        im[mask] = crop[mask]
        if name == chain.get("image"):
            for (x0, y0, cols) in ((0, 0, MARK_TL), (bw - 2, bh - 2, MARK_BR)):
                for k, col in enumerate(cols):
                    im[y0 + k // 2, x0 + k % 2] = col
            chain["box"] = (bx, by, bw, bh)
        Image.fromarray(im).save(p)
        n += 1
    if "box" not in chain:
        raise SystemExit("panel_art: the PICTURES page's panel image was not found in TUI.json")
    bx, by, bw, bh = chain["box"]
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    open(os.path.join(ROOT, "build", "chain_box.h"), "w").write(
        "/* generated by tools/panel_art.py: the PICTURES page's panel image (%s) on the 1280x628 page */\n"
        "#define CB_PAGE_X %d\n#define CB_PAGE_Y %d\n#define CB_W %d\n#define CB_H %d\n" % (chain["image"], bx, by, bw, bh))
    print("panel_art: %d images; chain markers in %s at %d,%d %dx%d" % (n, chain["image"], bx, by, bw, bh))


if __name__ == "__main__":
    if sys.argv[1:2] == ["--preview"]:
        art().save(sys.argv[2])
    else:
        apply(sys.argv[1])
