/* THING4000: the chain's picture strip (L'Cronx).
 *
 * What it does: a grid of 8 big squares (4 x 2), one per block of the chain, each showing the picture that came with the capture loaded in
 * that block (a .png or .jpg next to the .nam / .wav), shrunk to fit inside its square; the selected block gets a bright
 * frame, a bypassed one is dimmed, an empty one is an outline.
 *
 * How: MPC draws the skin; a skin cannot show a picture that changes. So this file does what XYZ 0.0.2 does on the Force
 * (it worked on 3.9.1): a thread takes a spare hardware overlay plane of the display and draws the grid into it, only
 * while the PICTURES page is on screen. The page is found by two 2x2 marker pixel blocks that the skin build paints into the
 * PICTURES page's panel image (tools/panel_art.py, build/chain_box.h). The parts marked "from VADER" are VADER 0.5.0's
 * overlay code (sunskiefer/VADER src/overlay.c, MIT, same author), with XYZ's fixes (the shadowed variable, and the
 * search for the portrait panel's turn). No touch is read: tapping a square is the skin's own tile underneath.
 *
 * Everything it finds and does goes to "<data folder>/chain/chain.log". "<data folder>/chain/chain.off" switches it off.
 * "<data folder>/chain/layout.txt" holds the strip's place: a line "strip x y w h" in page pixels (the plugin page is
 * 1280 x 628); it is written with the default on first start, and moving it is the user's choice. */
