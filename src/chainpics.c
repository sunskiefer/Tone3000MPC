typedef struct { int used[CP_N], bypass[CP_N], sel, w[CP_N], h[CP_N]; uint8_t *px[CP_N]; } cp_snap_t;
struct cp_inst {
    cp_snap_t st;
    unsigned ver;            /* bumped (under g_lock) on any change */
    int on_page;             /* this instance's PICTURES page is the open page (set by the engine the moment the view changes) */
    int id;
    struct cp_inst *next;
};
static pthread_mutex_t g_lock = PTHREAD_MUTEX_INITIALIZER;
static struct cp_inst *g_list;
static struct cp_inst *g_active;      /* the instance whose page is (probably) on screen: the one the UI touched last */
static int g_users, g_next_id;
static overlay_t g_o;
static int g_thread_up;
static int g_strip_x = STRIP_X, g_strip_y = STRIP_Y, g_strip_w = STRIP_W, g_strip_h = STRIP_H;

/* ---- the log, at the place of the first instance's data folder ---- */
static void load_layout(overlay_t *o) {
    int x = STRIP_X, y = STRIP_Y, w = STRIP_W, h = STRIP_H;
    char path[800];
    snprintf(path, sizeof path, "%s/layout.txt", o->dir);
    FILE *f = fopen(path, "r");
    if (!f) {
        f = fopen(path, "w");
        if (f) {
            fprintf(f, "# THING4000 chain pictures: the picture grid (4 x 2 big squares), in page pixels (the plugin page is 1280 x 628, origin top-left).\n"
                       "# strip x y w h   -- move or resize it here; the default sits exactly over the PICTURES page's tile list.\n"
                       "strip %d %d %d %d\n", x, y, w, h);
            fclose(f);
        }
        logf_(o, "no layout.txt: the strip is at its default place %d,%d %dx%d (written to %s)", x, y, w, h, path);
    } else {
        char line[256];
        while (fgets(line, sizeof line, f)) {
            int a, b, c, d;
            if (line[0] == '#') continue;
            if (sscanf(line, " strip %d %d %d %d", &a, &b, &c, &d) == 4) { x = a; y = b; w = c; h = d; }
        }
        fclose(f);
    }
    if (w < 8 * 24 + 7 * 6) w = 8 * 24 + 7 * 6;
    if (h < 24) h = 24;
    if (w > 1280) w = 1280;
    if (h > 628) h = 628;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (x + w > 1280) x = 1280 - w;
    if (y + h > 628) y = 628 - h;
    g_strip_x = x; g_strip_y = y; g_strip_w = w; g_strip_h = h;
    o->pad_x = x - CB_PAGE_X; o->pad_y = y - CB_PAGE_Y; o->bw = w; o->bh = h;
    o->bufd = w > h ? w : h;   /* the plane's buffers are square, big enough for the strip turned either way */
    logf_(o, "layout.txt: strip at %d,%d, %dx%d (page pixels)", x, y, w, h);
}

/* ---- drawing: premultiplied ARGB (bytes B, G, R, A), in landscape ---- */
static inline void blend_px(uint8_t *p, float r, float g, float b, float a) {
    if (a <= 0) return;
    if (a > 1) a = 1;
    float ia = 1 - a;
    p[0] = (uint8_t)clampf_(b * a + p[0] * ia + 0.5f, 0, 255);
    p[1] = (uint8_t)clampf_(g * a + p[1] * ia + 0.5f, 0, 255);
    p[2] = (uint8_t)clampf_(r * a + p[2] * ia + 0.5f, 0, 255);
    p[3] = (uint8_t)clampf_(255 * a + p[3] * ia + 0.5f, 0, 255);
}
/* coverage 0..1 of a rounded rectangle (centre cx, cy; half sizes hw, hh; corner radius r) at a pixel centre */
static float rr_cov(float x, float y, float cx, float cy, float hw, float hh, float r) {
    float dx = fabsf(x - cx) - (hw - r), dy = fabsf(y - cy) - (hh - r);
    float ox = dx > 0 ? dx : 0, oy = dy > 0 ? dy : 0;
    float d = sqrtf(ox * ox + oy * oy) + (dx > dy ? (dx < 0 ? dx : 0) : (dy < 0 ? dy : 0)) - r;
    return clampf_(0.5f - d, 0, 1);
}

static const uint8_t DIG[8][7] = {   /* 5 x 7 digits 1..8, one row per byte */
    {0x04, 0x0c, 0x04, 0x04, 0x04, 0x04, 0x0e}, {0x0e, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1f},
    {0x1e, 0x01, 0x01, 0x0e, 0x01, 0x01, 0x1e}, {0x02, 0x06, 0x0a, 0x12, 0x1f, 0x02, 0x02},
    {0x1f, 0x10, 0x1e, 0x01, 0x01, 0x11, 0x0e}, {0x06, 0x08, 0x10, 0x1e, 0x11, 0x11, 0x0e},
    {0x1f, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}, {0x0e, 0x11, 0x11, 0x0e, 0x11, 0x11, 0x0e}};

static void draw_digit(uint8_t *out, int W, int H, int n, float cx, float cy, int k, float r, float g, float b) {
    int x0 = (int)(cx - 2.5f * k + 0.5f), y0 = (int)(cy - 3.5f * k + 0.5f);
    for (int row = 0; row < 7; row++)
        for (int col = 0; col < 5; col++)
            if (DIG[n][row] & (0x10 >> col))
                for (int dy = 0; dy < k; dy++)
                    for (int dx = 0; dx < k; dx++) {
                        int x = x0 + col * k + dx, y = y0 + row * k + dy;
                        if (x >= 0 && x < W && y >= 0 && y < H) blend_px(out + ((size_t)y * W + x) * 4, r, g, b, 1);
                    }
}

static void draw_card(uint8_t *out, int W, int H, const cp_snap_t *sn, int i, int x0, int y0, int cw, int chh) {
    int used = sn->used[i], sel = sn->sel == i, byp = sn->bypass[i] && used;
    float cx = x0 + cw / 2.0f, cy = y0 + chh / 2.0f, hw = cw / 2.0f, hh = chh / 2.0f, R = fminf(cw, chh) * 0.09f;
    float bw = sel ? 4.0f : 3.0f;
    /* colours: the card, its frame (bright yellow when selected) */
    float fr = 58, fg = 58, fb = 58, fa = 1.0f;
    float br = 200, bg = 200, bb = 200;
    if (!used) { br = bg = bb = 130; fr = fg = fb = 34; }
    if (byp) { br = bg = bb = 140; }
    if (sel) { br = 255; bg = 196; bb = 40; }
    for (int y = y0; y < y0 + chh; y++)
        for (int x = x0; x < x0 + cw; x++) {
            float px = x + 0.5f, py = y + 0.5f;
            float co = rr_cov(px, py, cx, cy, hw, hh, R), ci = rr_cov(px, py, cx, cy, hw - bw, hh - bw, R - bw);
            uint8_t *p = out + ((size_t)y * W + x) * 4;
            blend_px(p, fr, fg, fb, fa * ci);
            blend_px(p, br, bg, bb, co - ci);
        }
    float ihw = hw - bw - 6.0f, ihh = hh - bw - 6.0f;   /* half sizes of the area the picture may use */
    if (used && sn->px[i]) {
        int pw = sn->w[i], ph = sn->h[i];
        float sc = fminf(2 * ihw / pw, 2 * ihh / ph);
        float dw = pw * sc, dh = ph * sc;
        int ax = (int)floorf(cx - dw / 2), ay = (int)floorf(cy - dh / 2), bx = (int)ceilf(cx + dw / 2), by = (int)ceilf(cy + dh / 2);
        float dim = byp ? 0.45f : 1.0f;
        for (int y = ay; y < by; y++)
            for (int x = ax; x < bx; x++) {
                if (x < 0 || y < 0 || x >= W || y >= H) continue;
                float cov = rr_cov(x + 0.5f, y + 0.5f, cx, cy, dw / 2, dh / 2, fminf(6.0f, fminf(dw, dh) / 4));
                if (cov <= 0) continue;
                float sx0 = (x - (cx - dw / 2)) / sc, sx1 = (x + 1 - (cx - dw / 2)) / sc, sy0 = (y - (cy - dh / 2)) / sc, sy1 = (y + 1 - (cy - dh / 2)) / sc;
                int ix0 = (int)floorf(sx0), ix1 = (int)ceilf(sx1), iy0 = (int)floorf(sy0), iy1 = (int)ceilf(sy1);
                if (ix0 < 0) ix0 = 0; if (iy0 < 0) iy0 = 0; if (ix1 > pw) ix1 = pw; if (iy1 > ph) iy1 = ph;
                if (ix1 <= ix0) ix1 = ix0 + 1 > pw ? pw : ix0 + 1;
                if (iy1 <= iy0) iy1 = iy0 + 1 > ph ? ph : iy0 + 1;
                float ar = 0, ag = 0, ab = 0, aa = 0;
                int cnt = 0;
                for (int yy = iy0; yy < iy1; yy++)
                    for (int xx = ix0; xx < ix1; xx++) {
                        const uint8_t *q = sn->px[i] + ((size_t)yy * pw + xx) * 4;
                        float a = q[3] / 255.0f;
                        ar += q[0] * a; ag += q[1] * a; ab += q[2] * a; aa += a;
                        cnt++;
                    }
                if (!cnt || aa <= 0) continue;
                float a = aa / cnt;
                blend_px(out + ((size_t)y * W + x) * 4, dim * ar / aa, dim * ag / aa, dim * ab / aa, a * cov);
            }
    } else {
        /* no picture: the block's number, big */
        float r = 255, g = 255, b = 255;
        if (!used) r = g = b = 150;
        else if (byp) r = g = b = 170;
        if (sel) { r = 255; g = 196; b = 40; }
        int k = (int)(fminf(cw, chh) / 11);
        if (k < 2) k = 2;
        draw_digit(out, W, H, i, cx, cy, k, r, g, b);
    }
}

static void render_snap(const cp_snap_t *sn, int W, int H, uint8_t *out) {
    memset(out, 0, (size_t)W * H * 4);
    int gap = GRID_GAP;
    int cw = (W - (GRID_COLS - 1) * gap) / GRID_COLS, chh = (H - (GRID_ROWS - 1) * gap) / GRID_ROWS;
    if (cw < 8 || chh < 8) return;
    for (int i = 0; i < CP_N && i < GRID_COLS * GRID_ROWS; i++) {      /* row by row, like the tile list underneath */
        int col = i % GRID_COLS, row = i / GRID_COLS;
        draw_card(out, W, H, sn, i, col * (cw + gap), row * (chh + gap), cw, chh);
    }
}

/* ---- the engine's calls ---- */
struct cp_inst *cp_open(const char *data_dir, int run_overlay) {
    struct cp_inst *c = calloc(1, sizeof *c);
    if (!c) return NULL;
    pthread_mutex_lock(&g_lock);
    c->id = ++g_next_id;
    c->ver = 1;
    c->next = g_list; g_list = c;
    if (!g_active) g_active = c;
    g_users++;
    int first = run_overlay && !g_thread_up && data_dir && data_dir[0];
    if (first) g_thread_up = 1;
    pthread_mutex_unlock(&g_lock);
    if (first) cp_overlay_start(data_dir);
    return c;
}

void cp_close(struct cp_inst *c) {
    if (!c) return;
    pthread_mutex_lock(&g_lock);
    struct cp_inst **pp = &g_list;
    while (*pp && *pp != c) pp = &(*pp)->next;
    if (*pp) *pp = c->next;
    if (g_active == c) g_active = g_list;
    int last = --g_users == 0;
    pthread_mutex_unlock(&g_lock);
    if (last) cp_overlay_stop();
    pthread_mutex_lock(&g_lock);
    for (int i = 0; i < CP_N; i++) free(c->st.px[i]);
    pthread_mutex_unlock(&g_lock);
    free(c);
}

void cp_touch(struct cp_inst *c) { __atomic_store_n(&g_active, c, __ATOMIC_RELAXED); }

void cp_set_page(struct cp_inst *c, int open) {
    if (!c) return;
    open = open ? 1 : 0;
    if (__atomic_load_n(&c->on_page, __ATOMIC_RELAXED) == open) return;
    __atomic_store_n(&c->on_page, open, __ATOMIC_RELAXED);
    pthread_mutex_lock(&g_lock);
    c->ver++;
    pthread_mutex_unlock(&g_lock);
    if (open) __atomic_store_n(&g_active, c, __ATOMIC_RELAXED);   /* the page that was just opened is the one on screen */
}

/* is the active instance's PICTURES page open? (the grid is hidden the moment it is not, without waiting for the marker search) */
static int active_page_open(void) {
    struct cp_inst *a = __atomic_load_n(&g_active, __ATOMIC_RELAXED);
    return a && __atomic_load_n(&a->on_page, __ATOMIC_RELAXED);
}

void cp_set_state(struct cp_inst *c, const int *used, const int *bypass, int sel) {
    pthread_mutex_lock(&g_lock);
    int ch = 0;
    for (int i = 0; i < CP_N; i++) {
        if (c->st.used[i] != used[i]) { c->st.used[i] = used[i]; ch = 1; }
        if (c->st.bypass[i] != bypass[i]) { c->st.bypass[i] = bypass[i]; ch = 1; }
    }
    if (c->st.sel != sel) { c->st.sel = sel; ch = 1; }
    if (ch) c->ver++;
    pthread_mutex_unlock(&g_lock);
}

void cp_set_picture(struct cp_inst *c, int blk, const uint8_t *rgba, int w, int h) {
    if (blk < 0 || blk >= CP_N) return;
    uint8_t *copy = NULL;
    if (rgba && w > 0 && h > 0 && w <= CP_MAXPIC && h <= CP_MAXPIC) {
        copy = malloc((size_t)w * h * 4);
        if (copy) memcpy(copy, rgba, (size_t)w * h * 4);
    }
    pthread_mutex_lock(&g_lock);
    uint8_t *old = c->st.px[blk];
    c->st.px[blk] = copy; c->st.w[blk] = copy ? w : 0; c->st.h[blk] = copy ? h : 0;
    c->ver++;
    pthread_mutex_unlock(&g_lock);
    free(old);
}

int cp_render(struct cp_inst *c, uint8_t *out, int cap, int *w, int *h) {
    *w = STRIP_W; *h = STRIP_H;
    if (cap < STRIP_W * STRIP_H * 4) return -1;
    pthread_mutex_lock(&g_lock);
    render_snap(&c->st, STRIP_W, STRIP_H, out);
    pthread_mutex_unlock(&g_lock);
    return 0;
}

/* ---- the thread ---- */
static double now_ms(void) { struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts); return ts.tv_sec * 1e3 + ts.tv_nsec / 1e6; }

/* a private copy of the active instance's state for drawing, refreshed only when something changed */
static void snap_take(cp_snap_t *dst, unsigned *seen_ver, struct cp_inst **seen_inst, int *changed) {
    pthread_mutex_lock(&g_lock);
    struct cp_inst *a = __atomic_load_n(&g_active, __ATOMIC_RELAXED);
    if (!a) a = g_list;
    *changed = 0;
    if (a && (a != *seen_inst || a->ver != *seen_ver)) {
        for (int i = 0; i < CP_N; i++) {
            free(dst->px[i]); dst->px[i] = NULL;
            dst->used[i] = a->st.used[i]; dst->bypass[i] = a->st.bypass[i];
            dst->w[i] = a->st.w[i]; dst->h[i] = a->st.h[i];
            if (a->st.px[i]) { size_t n = (size_t)a->st.w[i] * a->st.h[i] * 4; dst->px[i] = malloc(n); if (dst->px[i]) memcpy(dst->px[i], a->st.px[i], n); else dst->w[i] = dst->h[i] = 0; }
        }
        dst->sel = a->st.sel;
        *seen_ver = a->ver; *seen_inst = a;
        *changed = 1;
    }
    pthread_mutex_unlock(&g_lock);
}

static void *strip_thread(void *p) {
    overlay_t *o = p;
    logf_(o, "THING4000 chain pictures starting");
    uint8_t *land = NULL, *rotf = NULL, *prev = NULL;
    cp_snap_t sn;
    memset(&sn, 0, sizeof sn);
    int tries = 0;
    while (!o->stop && drm_setup(o)) {
        for (int i = 0; i < 2; i++) destroy_buffer(o, &o->buf[i]);
        if (++tries >= 3) { logf_(o, "giving up: no picture strip (everything else works as before)"); goto done; }
        logf_(o, "retry %d in 3 s", tries);
        for (int i = 0; i < 30 && !o->stop; i++) usleep(100000);
    }
    if (o->stop) goto done;
    land = malloc((size_t)o->bw * o->bh * 4);
    rotf = calloc((size_t)o->bufd * o->bufd, 4);
    prev = calloc((size_t)o->bufd * o->bufd, 4);
    if (!land || !rotf || !prev) { logf_(o, "no memory"); goto done; }
    __atomic_store_n(&o->live, 1, __ATOMIC_RELEASE);
    logf_(o, "live");
    int shown = 0, first = 1, fails = 0, looks = 0, dirty = 1;
    unsigned geom_seen = ~0u, seen_ver = 0;
    struct cp_inst *seen_inst = NULL;
    double last_look = 0, last_draw = 0, last_stat = now_ms();
    long frames = 0;
    while (!o->stop) {
        usleep(20000);
        double now = now_ms();
        if (now - last_look >= 100) {   /* 10 looks a second at the display's picture; a whole-picture search twice a second while the page isn't found */
            int on = locate(o, (looks++ % 5) == 0);
            if (on != o->on_screen) logf_(o, "Chain page %s", on ? "on screen" : "not on screen");
            o->on_screen = on;
            last_look = now;
        }
        int on = o->on_screen && !o->fmt_unknown && o->have_page && active_page_open();
        if (on) {
            int ch = 0;
            snap_take(&sn, &seen_ver, &seen_inst, &ch);
            if (ch) dirty = 1;
            unsigned geom = o->geom;
            if (first || geom != geom_seen || dirty || !shown) {
                if (now - last_draw >= 10) {
                    if (geom != geom_seen) first = 1;   /* the plane moved or turned: a whole new picture */
                    render_snap(&sn, o->bw, o->bh, land);
                    rotate_strip(o, land, rotf);
                    if (!o->no_vblank) {
                        union drm_wait_vblank wv;
                        memset(&wv, 0, sizeof wv);
                        wv.request.type = _DRM_VBLANK_RELATIVE | (o->crtc_index ? (unsigned)(o->crtc_index << _DRM_VBLANK_HIGH_CRTC_SHIFT) & _DRM_VBLANK_HIGH_CRTC_MASK : 0);
                        wv.request.sequence = 1;
                        if (xioctl(o->fd, DRM_IOCTL_WAIT_VBLANK, &wv)) { o->no_vblank = 1; logf_(o, "WAIT_VBLANK: %s (copying without it)", strerror(errno)); }
                    }
                    ovl_buf_t *b = &o->buf[0];
                    for (int yy = 0; yy < o->ph; yy++) {
                        const uint8_t *src = rotf + (size_t)yy * o->pw * 4;
                        uint8_t *pv = prev + (size_t)yy * o->pw * 4;
                        if (!first && !memcmp(src, pv, (size_t)o->pw * 4)) continue;
                        memcpy(b->map + (size_t)yy * b->pitch, src, (size_t)o->pw * 4);
                        memcpy(pv, src, (size_t)o->pw * 4);
                    }
                    int replace = !shown || geom != geom_seen;
                    first = 0; dirty = 0; last_draw = now; frames++; geom_seen = geom;
                    if (replace) {
                        if (set_plane(o, b->fb_id, o->pl_x, o->pl_y)) {
                            if (++fails == 1 || fails % 300 == 0) logf_(o, "SETPLANE: %s (%d so far)", strerror(errno), fails);
                            if (errno == EACCES || errno == EPERM) { logf_(o, "not the display's master: no picture strip"); break; }
                            shown = 0;
                        } else { shown = 1; logf_(o, "shown: plane at %d,%d, %dx%d on the display", o->pl_x, o->pl_y, o->pw, o->ph); }
                    }
                }
            }
        } else if (shown) {
            set_plane(o, 0, 0, 0);
            shown = 0; first = 1;
            logf_(o, "hidden (%s)", o->fmt_unknown ? "the display's picture can't be read" : "THING4000's Chain page is not on the display");
        }
        if (now - last_stat >= 30000) {
            logf_(o, "%ld frames, %s", frames, shown ? "shown" : "hidden");
            last_stat = now;
        }
    }
    set_plane(o, 0, 0, 0);
    for (int i = 0; i < 2; i++) destroy_buffer(o, &o->buf[i]);
    __atomic_store_n(&o->live, 0, __ATOMIC_RELEASE);
    logf_(o, "stopped");
done:
    for (int i = 0; i < CP_N; i++) free(sn.px[i]);
    free(land); free(rotf); free(prev);
    return NULL;
}

void cp_overlay_start(const char *data_dir) {
    overlay_t *o = &g_o;
    memset(o, 0, sizeof *o);
    o->fd = -1;
    char sub[700];
    snprintf(sub, sizeof sub, "%s/chain", data_dir);
    mkdir(sub, 0755);
    snprintf(o->dir, sizeof o->dir, "%s", sub);
    char off[760];
    snprintf(off, sizeof off, "%s/chain.off", sub);
    if (access(off, F_OK) == 0) { pthread_mutex_lock(&g_lock); g_thread_up = 0; pthread_mutex_unlock(&g_lock); return; }
    snprintf(o->log_path, sizeof o->log_path, "%s/chain.log", sub);
    FILE *f = fopen(o->log_path, "w");   /* a fresh log each start */
    if (f) fclose(f); else { o->log_path[0] = 0; pthread_mutex_lock(&g_lock); g_thread_up = 0; pthread_mutex_unlock(&g_lock); return; }
    if (access("/proc/self/fd", R_OK)) { pthread_mutex_lock(&g_lock); g_thread_up = 0; pthread_mutex_unlock(&g_lock); return; }
    load_layout(o);
    o->started = 1;
    if (pthread_create(&o->thread, NULL, strip_thread, o)) { o->started = 0; logf_(o, "no thread"); pthread_mutex_lock(&g_lock); g_thread_up = 0; pthread_mutex_unlock(&g_lock); }
}

void cp_overlay_stop(void) {
    overlay_t *o = &g_o;
    if (!o->started) { pthread_mutex_lock(&g_lock); g_thread_up = 0; pthread_mutex_unlock(&g_lock); return; }
    o->stop = 1;
    pthread_join(o->thread, NULL);
    o->started = 0;
    pthread_mutex_lock(&g_lock);
    g_thread_up = 0;
    pthread_mutex_unlock(&g_lock);
}
